"""Task intake service.

Coordinates task lifecycle operations: create, list, get, plan, approve,
reject, and cancel. TaskService composes the TaskStorage port, M2
ProjectService (project lookup), M3 ProjectProfiler (profiling during
planning), a TaskPlanner, and an ActorResolver. It contains no JSON
serialization, planning heuristics, or execution-plane behavior.

All task IDs are generated by the service (``task_`` prefix) and validated
against path traversal before being used in storage paths.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Any, List

from factory.control.actor import ActorResolver
from factory.control.projects.service import ProjectService
from factory.control.task_models import LifecycleEvent, TaskRecord, TaskStatus
from factory.control.task_storage import TaskStorage
from factory.intelligence.engine import ProjectProfiler
from factory.errors import TaskNotFoundError, TaskValidationError

TASK_ID_PREFIX = "task_"


class TaskService:
    """Application workflow for task intake and lifecycle management.

    The service depends on injected ports so persistence, project lookup,
    profiling, planning, and actor resolution can be swapped or tested in
    isolation. TaskService coordinates dependencies but does not implement
    their internal functionality.

    Attributes:
        storage: Persistence port for task records.
        project_service: M2 project lookup service.
        profiler: M3 project profiler (used only during plan_task).
        planner: TaskPlanner implementation (used only during plan_task).
        actor_resolver: Resolves actor identity for lifecycle attribution.
    """

    def __init__(
        self,
        storage: TaskStorage,
        project_service: ProjectService,
        profiler: ProjectProfiler,
        planner: "TaskPlanner",
        actor_resolver: ActorResolver,
    ) -> None:
        self._storage = storage
        self._project_service = project_service
        self._profiler = profiler
        self._planner = planner
        self._actor_resolver = actor_resolver

    def create_task(self, project_id: str, description: str) -> TaskRecord:
        """Register a new task in ``created`` state for a project.

        Args:
            project_id: Identifier of a registered project.
            description: User-provided task description.

        Returns:
            The newly created :class:`TaskRecord`.

        Raises:
            TaskValidationError: If ``project_id`` or ``description`` is
                empty.
            ProjectNotFoundError: If no project has ``project_id`` (raised
                by M2 ``ProjectService.get_project``).
        """
        if not project_id or not project_id.strip():
            raise TaskValidationError(
                "Project ID must not be empty", detail=project_id
            )
        if not description or not description.strip():
            raise TaskValidationError(
                "Task description must not be empty", detail=description
            )

        # Verify the project exists via M2 ProjectService; no lookup logic
        # is duplicated here.
        self._project_service.get_project(project_id)

        task_id = f"{TASK_ID_PREFIX}{uuid.uuid4().hex}"
        now = datetime.now(timezone.utc)
        record = TaskRecord(
            task_id=task_id,
            project_id=project_id,
            description=description,
            status=TaskStatus.CREATED,
            created_at=now,
            updated_at=now,
            current_revision=None,
        )
        record.lifecycle_history.append(
            LifecycleEvent(
                from_status=None,
                to_status=TaskStatus.CREATED,
                timestamp=now,
                actor=None,
            )
        )
        self._storage.save(task_id, record)
        return record

    def list_tasks(self) -> List[TaskRecord]:
        """Return all registered task records."""
        return self._storage.list_all()

    def get_task(self, task_id: str) -> TaskRecord:
        """Return the complete task record for ``task_id``.

        Args:
            task_id: Stable task identifier with the ``task_`` prefix.

        Returns:
            The matching :class:`TaskRecord`.

        Raises:
            TaskValidationError: If ``task_id`` is empty, malformed, or
                attempts path traversal.
            TaskNotFoundError: If no task has the given identifier.
            TaskStorageError: If the stored record is corrupted.
        """
        self._validate_task_id(task_id)
        record = self._storage.load(task_id)
        if record is None:
            raise TaskNotFoundError(
                f"Unknown task id: {task_id}", detail=task_id
            )
        return record

    def _validate_task_id(self, task_id: str) -> None:
        """Reject empty, malformed, or path-traversal task IDs."""
        if not task_id or not task_id.strip():
            raise TaskValidationError(
                "Task ID must not be empty", detail=task_id
            )
        if not task_id.startswith(TASK_ID_PREFIX):
            raise TaskValidationError(
                f"Invalid task ID format: {task_id!r}",
                detail=f"task IDs must use the '{TASK_ID_PREFIX}' prefix",
            )
        if "/" in task_id or "\\" in task_id or ".." in task_id:
            raise TaskValidationError(
                f"Task ID contains invalid path characters: {task_id!r}",
                detail="path traversal is not allowed",
            )
