"""Task intake service.

Coordinates task lifecycle operations: create, list, get, plan, approve,
reject, and cancel. TaskService composes the TaskStorage port, M2
ProjectService (project lookup), M3 ProjectProfiler (profiling during
planning), a TaskPlanner, and an ActorResolver. It contains no JSON
serialization, planning heuristics, or execution-plane behavior.

All task IDs are generated by the service (``task_`` prefix) and validated
against path traversal before being used in storage paths.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import List, Optional

from factory.control.actor import ActorResolver
from factory.control.planner import TaskPlanner
from factory.control.projects.service import ProjectService
from factory.control.task_models import (
    ApprovalRecord,
    ImplementationPlan,
    LifecycleEvent,
    PlanRevision,
    TaskRecord,
    TaskStatus,
)
from factory.control.task_storage import TaskStorage
from factory.intelligence.engine import ProjectProfiler
from factory.errors import (
    ActorResolutionError,
    InvalidTaskTransitionError,
    PlanValidationError,
    PlanningError,
    ProjectInspectionError,
    ProjectNotFoundError,
    TaskNotFoundError,
    TaskValidationError,
)

TASK_ID_PREFIX = "task_"


class TaskService:
    """Application workflow for task intake and lifecycle management.

    The service depends on injected ports so persistence, project lookup,
    profiling, planning, and actor resolution can be swapped or tested in
    isolation. TaskService coordinates dependencies but does not implement
    their internal functionality.

    Attributes:
        storage: Persistence port for task records.
        project_service: M2 project lookup service.
        profiler: M3 project profiler (used only during plan_task).
        planner: TaskPlanner implementation (used only during plan_task).
        actor_resolver: Resolves actor identity for lifecycle attribution.
    """

    def __init__(
        self,
        storage: TaskStorage,
        project_service: ProjectService,
        profiler: ProjectProfiler,
        planner: "TaskPlanner",
        actor_resolver: ActorResolver,
    ) -> None:
        self._storage = storage
        self._project_service = project_service
        self._profiler = profiler
        self._planner = planner
        self._actor_resolver = actor_resolver

    def create_task(self, project_id: str, description: str) -> TaskRecord:
        """Register a new task in ``created`` state for a project.

        Args:
            project_id: Identifier of a registered project.
            description: User-provided task description.

        Returns:
            The newly created :class:`TaskRecord`.

        Raises:
            TaskValidationError: If ``project_id`` or ``description`` is
                empty.
            ProjectNotFoundError: If no project has ``project_id`` (raised
                by M2 ``ProjectService.get_project``).
        """
        if not project_id or not project_id.strip():
            raise TaskValidationError(
                "Project ID must not be empty", detail=project_id
            )
        if not description or not description.strip():
            raise TaskValidationError(
                "Task description must not be empty", detail=description
            )

        # Verify the project exists via M2 ProjectService; no lookup logic
        # is duplicated here.
        self._project_service.get_project(project_id)

        task_id = f"{TASK_ID_PREFIX}{uuid.uuid4().hex}"
        now = datetime.now(timezone.utc)
        record = TaskRecord(
            task_id=task_id,
            project_id=project_id,
            description=description,
            status=TaskStatus.CREATED,
            created_at=now,
            updated_at=now,
            current_revision=None,
        )
        record.lifecycle_history.append(
            LifecycleEvent(
                from_status=None,
                to_status=TaskStatus.CREATED,
                timestamp=now,
                actor=None,
            )
        )
        self._storage.save(task_id, record)
        return record

    def list_tasks(self) -> List[TaskRecord]:
        """Return all registered task records."""
        return self._storage.list_all()

    def get_task(self, task_id: str) -> TaskRecord:
        """Return the complete task record for ``task_id``.

        Args:
            task_id: Stable task identifier with the ``task_`` prefix.

        Returns:
            The matching :class:`TaskRecord`.

        Raises:
            TaskValidationError: If ``task_id`` is empty, malformed, or
                attempts path traversal.
            TaskNotFoundError: If no task has the given identifier.
            TaskStorageError: If the stored record is corrupted.
        """
        self._validate_task_id(task_id)
        record = self._storage.load(task_id)
        if record is None:
            raise TaskNotFoundError(
                f"Unknown task id: {task_id}", detail=task_id
            )
        return record

    def _validate_task_id(self, task_id: str) -> None:
        """Reject empty, malformed, or path-traversal task IDs."""
        if not task_id or not task_id.strip():
            raise TaskValidationError(
                "Task ID must not be empty", detail=task_id
            )
        if not task_id.startswith(TASK_ID_PREFIX):
            raise TaskValidationError(
                f"Invalid task ID format: {task_id!r}",
                detail=f"task IDs must use the '{TASK_ID_PREFIX}' prefix",
            )
        if "/" in task_id or "\\" in task_id or ".." in task_id:
            raise TaskValidationError(
                f"Task ID contains invalid path characters: {task_id!r}",
                detail="path traversal is not allowed",
            )

    def plan_task(self, task_id: str) -> TaskRecord:
        """Generate an implementation plan for ``task_id``.

        Transitions the task to ``planning`` at start, then to
        ``awaiting_approval`` on success. On failure, reverts to the
        pre-planning status and preserves all revisions and approvals.

        For an ``approved`` task, generates a candidate plan without
        changing persisted state. If the candidate is equivalent to the
        current approved revision's plan, the existing revision and
        approval are retained and the task remains ``approved``. If
        materially different, a new revision is appended, the previous
        approved revision is marked ``superseded``, and the task
        transitions to ``awaiting_approval``.

        Args:
            task_id: Stable task identifier with the ``task_`` prefix.

        Returns:
            The updated :class:`TaskRecord`.

        Raises:
            TaskValidationError: If ``task_id`` is invalid.
            TaskNotFoundError: If no task has ``task_id``.
            InvalidTaskTransitionError: If the task is in
                ``awaiting_approval`` or ``cancelled`` state.
            ProjectNotFoundError: If the task's project is unknown.
            ProjectInspectionError: If project profiling fails.
            PlanningError: If plan generation fails.
            PlanValidationError: If the generated plan is invalid.
        """
        self._validate_task_id(task_id)
        record = self._storage.load(task_id)
        if record is None:
            raise TaskNotFoundError(
                f"Unknown task id: {task_id}", detail=task_id
            )

        original_status = record.status
        now = datetime.now(timezone.utc)

        # Reject transitions that are not permitted.
        if original_status == TaskStatus.AWAITING_APPROVAL:
            raise InvalidTaskTransitionError(
                f"Cannot plan task {task_id} in awaiting_approval state",
                detail="Approve or reject the current plan first.",
            )
        if original_status == TaskStatus.CANCELLED:
            raise InvalidTaskTransitionError(
                f"Cannot plan cancelled task {task_id}",
                detail="Cancelled is a terminal state.",
            )

        # For approved tasks, check candidate-plan equivalence before any
        # persisted state change.
        if original_status == TaskStatus.APPROVED:
            plan = self._profile_and_plan(record)
            current_revision = self._get_current_revision(record)
            if current_revision is not None and plan == current_revision.plan:
                # Equivalent: retain existing revision and approval.
                return record
            # Materially different: mark previous revision superseded.
            current_revision.status = "superseded"

        # For created / rejected: transition to planning first.
        else:
            record.status = TaskStatus.PLANNING
            record.updated_at = now
            record.lifecycle_history.append(
                LifecycleEvent(
                    from_status=original_status,
                    to_status=TaskStatus.PLANNING,
                    timestamp=now,
                    actor=None,
                )
            )

        try:
            plan = self._profile_and_plan(record)

            # Append new revision and transition to awaiting_approval.
            new_revision_number = self._next_revision_number(record)
            new_revision = PlanRevision(
                revision_number=new_revision_number,
                created_at=now,
                status="awaiting_approval",
                plan=plan,
                approval=None,
            )
            record.plan_revisions.append(new_revision)
            record.current_revision = new_revision_number
            record.status = TaskStatus.AWAITING_APPROVAL
            record.updated_at = now
            record.lifecycle_history.append(
                LifecycleEvent(
                    from_status=TaskStatus.PLANNING,
                    to_status=TaskStatus.AWAITING_APPROVAL,
                    timestamp=now,
                    actor=None,
                )
            )

            self._storage.save(task_id, record)
            return record

        except (
            ProjectNotFoundError,
            ProjectInspectionError,
            PlanningError,
            PlanValidationError,
        ):
            # Revert to pre-planning status; preserve revisions.
            record.status = original_status
            record.updated_at = now
            record.lifecycle_history.append(
                LifecycleEvent(
                    from_status=TaskStatus.PLANNING,
                    to_status=original_status,
                    timestamp=now,
                    actor=None,
                )
            )
            self._storage.save(task_id, record)
            raise

    def approve_task(self, task_id: str) -> TaskRecord:
        """Approve the current plan revision for ``task_id``.

        Resolves the actor via :class:`ActorResolver`, records an
        :class:`ApprovalRecord` on the current revision, and transitions
        the task to ``approved``.

        Args:
            task_id: Stable task identifier with the ``task_`` prefix.

        Returns:
            The updated :class:`TaskRecord`.

        Raises:
            TaskValidationError: If ``task_id`` is invalid.
            TaskNotFoundError: If no task has ``task_id``.
            InvalidTaskTransitionError: If the task is not in
                ``awaiting_approval`` state or has no current revision.
            ActorResolutionError: If the actor cannot be resolved.
        """
        self._validate_task_id(task_id)
        record = self._storage.load(task_id)
        if record is None:
            raise TaskNotFoundError(
                f"Unknown task id: {task_id}", detail=task_id
            )

        if record.status != TaskStatus.AWAITING_APPROVAL:
            raise InvalidTaskTransitionError(
                f"Cannot approve task {task_id} in {record.status.value} state",
                detail="Task must be awaiting_approval.",
            )

        current_revision = self._get_current_revision(record)
        if current_revision is None:
            raise InvalidTaskTransitionError(
                f"Cannot approve task {task_id}: no current revision",
                detail="A plan revision must exist before approval.",
            )

        actor = self._resolve_actor()

        now = datetime.now(timezone.utc)
        current_revision.status = "approved"
        current_revision.approval = ApprovalRecord(
            decision="approved",
            actor=actor,
            timestamp=now,
            reason=None,
        )
        record.status = TaskStatus.APPROVED
        record.updated_at = now
        record.lifecycle_history.append(
            LifecycleEvent(
                from_status=TaskStatus.AWAITING_APPROVAL,
                to_status=TaskStatus.APPROVED,
                timestamp=now,
                actor=actor,
                reason=None,
            )
        )

        self._storage.save(task_id, record)
        return record

    def reject_task(self, task_id: str, reason: str) -> TaskRecord:
        """Reject the current plan revision for ``task_id``.

        Resolves the actor via :class:`ActorResolver`, records an
        :class:`ApprovalRecord` with the reason on the current revision,
        and transitions the task to ``rejected``.

        Args:
            task_id: Stable task identifier with the ``task_`` prefix.
            reason: Reason for rejection.

        Returns:
            The updated :class:`TaskRecord`.

        Raises:
            TaskValidationError: If ``task_id`` is invalid or ``reason``
                is empty.
            TaskNotFoundError: If no task has ``task_id``.
            InvalidTaskTransitionError: If the task is not in
                ``awaiting_approval`` state or has no current revision.
            ActorResolutionError: If the actor cannot be resolved.
        """
        self._validate_task_id(task_id)
        record = self._storage.load(task_id)
        if record is None:
            raise TaskNotFoundError(
                f"Unknown task id: {task_id}", detail=task_id
            )

        if not reason or not reason.strip():
            raise TaskValidationError(
                "Rejection reason must not be empty", detail=reason
            )

        if record.status != TaskStatus.AWAITING_APPROVAL:
            raise InvalidTaskTransitionError(
                f"Cannot reject task {task_id} in {record.status.value} state",
                detail="Task must be awaiting_approval.",
            )

        current_revision = self._get_current_revision(record)
        if current_revision is None:
            raise InvalidTaskTransitionError(
                f"Cannot reject task {task_id}: no current revision",
                detail="A plan revision must exist before rejection.",
            )

        actor = self._resolve_actor()

        now = datetime.now(timezone.utc)
        current_revision.status = "rejected"
        current_revision.approval = ApprovalRecord(
            decision="rejected",
            actor=actor,
            timestamp=now,
            reason=reason.strip(),
        )
        record.status = TaskStatus.REJECTED
        record.updated_at = now
        record.lifecycle_history.append(
            LifecycleEvent(
                from_status=TaskStatus.AWAITING_APPROVAL,
                to_status=TaskStatus.REJECTED,
                timestamp=now,
                actor=actor,
                reason=reason.strip(),
            )
        )

        self._storage.save(task_id, record)
        return record

    def cancel_task(self, task_id: str) -> TaskRecord:
        """Cancel ``task_id`` when the current lifecycle state permits.

        Resolves the actor via :class:`ActorResolver` and transitions
        the task to ``cancelled`` (terminal state).

        Cancellation is permitted from ``created``, ``awaiting_approval``,
        ``approved``, and ``rejected``. It is disallowed from ``planning``
        and ``cancelled``.

        Args:
            task_id: Stable task identifier with the ``task_`` prefix.

        Returns:
            The updated :class:`TaskRecord`.

        Raises:
            TaskValidationError: If ``task_id`` is invalid.
            TaskNotFoundError: If no task has ``task_id``.
            InvalidTaskTransitionError: If cancellation is not permitted
                from the current state.
            ActorResolutionError: If the actor cannot be resolved.
        """
        self._validate_task_id(task_id)
        record = self._storage.load(task_id)
        if record is None:
            raise TaskNotFoundError(
                f"Unknown task id: {task_id}", detail=task_id
            )

        if record.status == TaskStatus.CANCELLED:
            raise InvalidTaskTransitionError(
                f"Cannot cancel task {task_id}: already cancelled",
                detail="Cancelled is a terminal state.",
            )
        if record.status == TaskStatus.PLANNING:
            raise InvalidTaskTransitionError(
                f"Cannot cancel task {task_id} in planning state",
                detail="Wait for planning to complete before cancelling.",
            )

        actor = self._resolve_actor()

        now = datetime.now(timezone.utc)
        original_status = record.status
        record.status = TaskStatus.CANCELLED
        record.updated_at = now
        record.lifecycle_history.append(
            LifecycleEvent(
                from_status=original_status,
                to_status=TaskStatus.CANCELLED,
                timestamp=now,
                actor=actor,
                reason=None,
            )
        )

        self._storage.save(task_id, record)
        return record

    def _resolve_actor(self) -> str:
        """Resolve the actor for lifecycle attribution.

        Returns:
            The resolved actor string.

        Raises:
            ActorResolutionError: If the actor cannot be resolved.
        """
        try:
            return self._actor_resolver.resolve()
        except ActorResolutionError:
            raise

    def _profile_and_plan(self, record: TaskRecord) -> ImplementationPlan:
        """Look up the project, profile it, and generate a plan.

        Wraps lower-level failures into domain exceptions without
        mutating the task record.
        """
        # Verify the project exists via M2 ProjectService.
        self._project_service.get_project(record.project_id)

        # Profile the project via M3 ProjectProfiler.
        try:
            profile = self._profiler.profile(record.project_id)
        except ProjectNotFoundError:
            raise
        except Exception as exc:  # pragma: no cover - infrastructure failure
            raise ProjectInspectionError(
                f"Project profiling failed for project {record.project_id}",
                detail=str(exc),
            ) from exc

        # Generate the plan via the injected TaskPlanner.
        try:
            plan = self._planner.create_plan(record.description, profile)
        except PlanningError:
            raise
        except Exception as exc:  # pragma: no cover - infrastructure failure
            raise PlanningError(
                f"Plan generation failed for task {record.task_id}",
                detail=str(exc),
            ) from exc

        # Validate the plan before any persistence.
        self._validate_plan(plan)
        return plan

    def _validate_plan(self, plan: ImplementationPlan) -> None:
        """Validate an ``ImplementationPlan`` before persistence.

        Raises:
            PlanValidationError: If the plan is structurally invalid.
        """
        if not plan.summary or not plan.summary.strip():
            raise PlanValidationError(
                "Plan summary is required", detail="summary"
            )

        step_numbers = [step.number for step in plan.implementation_steps]
        if len(step_numbers) != len(set(step_numbers)):
            raise PlanValidationError(
                "Step numbers must be unique within the plan",
                detail="implementation_steps",
            )

        existing_step_numbers = set(step_numbers)
        for step in plan.implementation_steps:
            for dep in step.depends_on:
                if dep == step.number:
                    raise PlanValidationError(
                        f"Step {step.number} cannot depend on itself",
                        detail="implementation_steps",
                    )
                if dep not in existing_step_numbers:
                    raise PlanValidationError(
                        f"Step {step.number} depends on unknown step {dep}",
                        detail="implementation_steps",
                    )

    def _get_current_revision(
        self, record: TaskRecord
    ) -> Optional[PlanRevision]:
        """Return the active :class:`PlanRevision`, or ``None``."""
        if record.current_revision is None:
            return None
        for revision in record.plan_revisions:
            if revision.revision_number == record.current_revision:
                return revision
        return None

    def _next_revision_number(self, record: TaskRecord) -> int:
        """Return the next sequential revision number for ``record``."""
        if not record.plan_revisions:
            return 1
        return max(r.revision_number for r in record.plan_revisions) + 1
